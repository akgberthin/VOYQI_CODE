#!/usr/bin/env python3
"""Regenerates infrastructure/kubernetes/base/kafka/topics.yaml — one
Strimzi KafkaTopic per topic any service publishes to — by scanning the
services' publish_event calls. Production Kafka doesn't auto-create
topics, so run this after adding a new topic:

    python3 scripts/generate_kafka_topics.py
    kubectl apply -k infrastructure/kubernetes/overlays/<env>/kafka
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "infrastructure" / "kubernetes" / "base" / "kafka" / "topics.yaml"

# publish_event(topic, event_type, tenant_id, payload) — topic passed literally
LITERAL_TOPIC = re.compile(r'publish_event,?\(?\s*\n?\s*"([a-z_.]+)",\s*(?:"[a-z_.]+"|[A-Z_]+\.get\(|\w+\.get\()')
# publish_event(event_type, payload) — topic is "<domain>.events" (build_envelope)
ENVELOPE_TOPIC = re.compile(r'publish_event\(\s*\n?\s*"([a-z_.]+)",\s*\n?\s*\{')
# helpers that wrap publish_event with a fixed topic
HELPER_TOPIC = re.compile(r'publish_event,?\(?\s*"([a-z_]+\.[a-z_]+)",\s*(?:event_type|DELIVERY_EVENT)')

HEADER = """# Generated by scripts/generate_kafka_topics.py — do not edit by hand.
#
# Every Kafka topic the platform publishes to. Production Kafka has
# auto.create.topics.enable=false (terraform/modules/kafka), so a topic
# missing here means its events are never delivered.
#
# Envelope on every topic: {event_type, tenant_id, occurred_at, payload}.
# Services publish to these domain topics; the AI nucleus subscribes to
# all of them by pattern and routes on event_type.
#
# Applied per environment with overlays/<env>/kafka, which sets the
# kafka namespace and the strimzi.io/cluster label.
"""


def scan() -> dict[str, set[str]]:
    topics: dict[str, set[str]] = {}
    for path in sorted((ROOT / "services").glob("*/src/**/*.py")):
        service = path.relative_to(ROOT / "services").parts[0]
        if service == "ai-orchestration-svc" or path.name == "kafka_events.py":
            continue
        text = path.read_text()
        found = set(LITERAL_TOPIC.findall(text)) | set(HELPER_TOPIC.findall(text))
        found |= {event.split(".")[0] + ".events" for event in ENVELOPE_TOPIC.findall(text)}
        for topic in found:
            topics.setdefault(topic, set()).add(service)
    return topics


def main() -> None:
    topics = scan()
    docs = [
        f"""apiVersion: kafka.strimzi.io/v1beta2
kind: KafkaTopic
metadata:
  name: {topic.replace('_', '-')}
  labels:
    strimzi.io/cluster: voyqi
  annotations:
    voyqi.io/published-by: "{', '.join(sorted(services))}"
spec:
  topicName: {topic}
  partitions: 3
  replicas: 3
  config:
    retention.ms: 604800000
    min.insync.replicas: 2
"""
        for topic, services in sorted(topics.items())
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "---\n".join(docs))
    print(f"{len(docs)} topics -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
