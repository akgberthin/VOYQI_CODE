# single alert, the same "meaningful accumulation" principle as
# safety scoring's every-5th-event reassessment.
TRIAGE_ALERT_COUNT_THRESHOLD = 3


async def list_open_unacknowledged_alerts(db: AsyncSession, tenant_id: str) -> list[MaintenanceAlert]:
    result = await db.execute(select(MaintenanceAlert).where(MaintenanceAlert.tenant_id == tenant_id, MaintenanceAlert.acknowledged == False))
    return list(result.scalars().all())


async def record_maintenance_triage(db: AsyncSession, tenant_id: str, alert_ids: list[str], priority_order: list[str], reasoning: str) -> MaintenanceTriageAssessment:
    assessment = MaintenanceTriageAssessment(tenant_id=tenant_id, alert_ids=alert_ids, priority_order=priority_order, reasoning=reasoning)
    db.add(assessment)
    await db.commit()
    await db.refresh(assessment)
    return assessment


async def auto_dispatch_top_priority_work_order(
    db: AsyncSession, tenant_id: str, priority_order: list[str], agent_key: str,
) -> WorkOrder | None:
    """Fully autonomous FLT-004 execution: after triage, the agent
    opens a work order for the single highest-priority alert
    immediately (vendor is a placeholder for the dispatch queue a real
    integration would route to) and acknowledges that alert so it
    drops out of the next triage batch. Lower-priority alerts stay
    open, unacknowledged, and visible for the next accumulation. A
    priority_order entry that isn't a real, existing alert ID (e.g. a
    stale ID from a batch that's already been processed) is skipped
    rather than raised — the triage record itself is always written
    regardless."""
    if not priority_order:
        return None
    top_alert_id = priority_order[0]
    try:
        alert_uuid = uuid.UUID(str(top_alert_id))
    except (ValueError, AttributeError, TypeError):
        return None
    alert_result = await db.execute(select(MaintenanceAlert).where(MaintenanceAlert.id == alert_uuid, MaintenanceAlert.tenant_id == tenant_id))
    alert = alert_result.scalar_one_or_none()
    if alert is None:
        return None

    order = await create_work_order(
        db, tenant_id, alert.vehicle_id, vendor="auto-dispatch-queue", created_by=agent_key,
        alert_id=alert.id, description=f"Auto-dispatched by Fleet Intelligence Agent — {alert.reason}",
    )
    alert.acknowledged = True
    await db.commit()
    await db.refresh(order)
    return order


async def get_latest_maintenance_triage(db: AsyncSession, tenant_id: str) -> MaintenanceTriageAssessment | None:
    result = await db.execute(select(MaintenanceTriageAssessment).where(MaintenanceTriageAssessment.tenant_id == tenant_id).order_by(MaintenanceTriageAssessment.computed_at.desc()))
    return result.scalars().first()
