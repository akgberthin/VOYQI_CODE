"""
FLT-004 Maintenance & Service Scheduler engine.

Predictive alerts are generated by plain threshold checks (mileage since
last service, DTC codes present) — deterministic on purpose. Pulling a
member's active vehicle for maintenance is consequential enough that the
trigger needs to be auditable arithmetic, not a model's judgment call.
Opening a work order for an URGENT alert moves the vehicle to
MAINTENANCE status automatically; ROUTINE/PREDICTIVE alerts don't.
"""
import uuid
from datetime import datetime, timezone

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from src.core.config import get_settings
from src.models import (
    MaintenanceAlert,
    MaintenanceAlertSeverity,
    MaintenanceTriageAssessment,
    Vehicle,
    VehicleStatus,
    WorkOrder,
    WorkOrderStatus,
)


async def evaluate_maintenance_need(
    db: AsyncSession, tenant_id: str, vehicle_id: uuid.UUID, miles_since_service: int, dtc_codes: list[str] | None = None
) -> MaintenanceAlert | None:
    settings = get_settings()
    dtc_codes = dtc_codes or []

    if dtc_codes:
        severity = MaintenanceAlertSeverity.URGENT
        reason = f"DTC code(s) present: {', '.join(dtc_codes)}"
    elif miles_since_service >= settings.maintenance_mileage_interval:
        severity = MaintenanceAlertSeverity.PREDICTIVE
        reason = f"{miles_since_service} miles since last service (interval: {settings.maintenance_mileage_interval})"
    else:
        return None

    alert = MaintenanceAlert(tenant_id=tenant_id, vehicle_id=vehicle_id, severity=severity, reason=reason, dtc_codes=dtc_codes)
    db.add(alert)
    await db.commit()
    await db.refresh(alert)
    return alert


async def create_work_order(
    db: AsyncSession, tenant_id: str, vehicle_id: uuid.UUID, vendor: str, created_by: str,
    alert_id: uuid.UUID | None = None, description: str = "",
) -> WorkOrder:
    order = WorkOrder(
        tenant_id=tenant_id, vehicle_id=vehicle_id, alert_id=alert_id, vendor=vendor,
        description=description, created_by=created_by,
    )
    db.add(order)

    if alert_id:
        alert_result = await db.execute(select(MaintenanceAlert).where(MaintenanceAlert.id == alert_id))
        alert = alert_result.scalar_one_or_none()
        if alert and alert.severity == MaintenanceAlertSeverity.URGENT:
            vehicle_result = await db.execute(select(Vehicle).where(Vehicle.id == vehicle_id))
            vehicle = vehicle_result.scalar_one_or_none()
            if vehicle:
                vehicle.status = VehicleStatus.MAINTENANCE

    await db.commit()
    await db.refresh(order)
    return order


async def complete_work_order(db: AsyncSession, tenant_id: str, work_order_id: uuid.UUID, cost_usd: float = 0.0) -> WorkOrder | None:
    result = await db.execute(select(WorkOrder).where(WorkOrder.id == work_order_id, WorkOrder.tenant_id == tenant_id))
    order = result.scalar_one_or_none()
    if order is None or order.status == WorkOrderStatus.COMPLETED:
        return None
    order.status = WorkOrderStatus.COMPLETED
    order.downtime_end = datetime.now(timezone.utc)
    order.cost_usd = cost_usd

    vehicle_result = await db.execute(select(Vehicle).where(Vehicle.id == order.vehicle_id))
    vehicle = vehicle_result.scalar_one_or_none()
    if vehicle and vehicle.status == VehicleStatus.MAINTENANCE:
        vehicle.status = VehicleStatus.STAGED

    await db.commit()
    await db.refresh(order)
    return order


def compute_downtime_hours(order: WorkOrder) -> float | None:
    if order.downtime_end is None:
        return None
    start = order.downtime_start
    end = order.downtime_end
    if start.tzinfo is None:
        start = start.replace(tzinfo=timezone.utc)
    if end.tzinfo is None:
        end = end.replace(tzinfo=timezone.utc)
    return (end - start).total_seconds() / 3600


